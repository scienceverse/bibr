"""Reference entries from a ``.docx`` reference list's own paragraphs.

A manuscript's reference list is typed, or generated by a reference manager,
one entry per paragraph. Read as body text, those paragraphs were joined and
split into sentences, and an LLM call put the entry boundaries back
(``segment_references``: a median of 1,277 output tokens per manuscript over
936 PsyArXiv manuscripts, with the 4B model on a GPU). When the paragraphs
pass a structure check they become ``PaperContents.native_ref_strings`` and
the reference extractor takes them as its segmentation; otherwise the
configured reference segmenter runs on the list as before.

Only a heading that is a reference list's name ("References", "7. Literature
Cited", "Supplementary References") heads such a list. One that only holds a
reference-list word ("Self-References in Memory", "Reference List
Searching") heads body text, whose dated paragraphs would pass the check.

A references section's list ends at its first float label, caption or
end-of-list heading ("Table 1", "Figure 2. ...", "Appendix", "Supplementary
Information", "Extended Data"): manuscripts put their tables and figures
after the references. An end-of-list word also opens some entries
("Supplementary Nutrition Assistance Program. (2020). ..."), so it ends the
list only in a paragraph shaped like a heading: at most
``MAX_END_HEADING_WORDS`` words, with no year and no byline. A later
references section (an appendix's own list) starts a new run of entries, and
so does a paragraph that is a reference list's name ("Supplemental
References", or "References" typed as a paragraph after a supplement under
the same heading); inside a list such a paragraph is skipped. A
supplementary heading directly followed by an entry (the supplement's own
references) does not end the list. The check then asks for at least
``MIN_ENTRIES`` entries of which ``MIN_YEAR_SHARE`` carry a year: entries
hard-wrapped into several paragraphs, and floats or notes the end rule
missed, leave paragraphs without one ("Journal of Sport Psychology, 6(1),
87–100.").

A paragraph whose explicit line breaks separate several entries is split at
them, when every line opens like an entry and gives a date ("(2019)",
"2019.", "n.d."): a journal line on a line of its own ("Psychological
Science, 31(12), 1601-1612.") stays in its entry. The strings are not
authoritative: the junk filter and the merged reference splitter still run
on them, as on HTML list items.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from bibr.input.heading_cues import (
    reads_as_float_label,
    reads_as_reference_heading,
    starts_as_caption,
)
from bibr.ocr.ref_patterns import _looks_like_author_date_start
from bibr.utils.text import YEARISH_RE

# A list this short is not worth trusting over the segmenter.
MIN_ENTRIES = 3
# Share of entries that must carry a year ("2020", "n.d.", "in press").
MIN_YEAR_SHARE = 0.9

# A heading over a reference list is at most this long; a longer "heading"
# that mentions references is a bold body paragraph ("Emotional Regulation:
# This category includes references to ...").
MAX_HEADING_CHARS = 60

# What may stand around a reference list's name, which the shared heading
# grammar (``reads_as_reference_heading``) reads with "7." or "VII." before
# it: numbering it does not take ("VII", "4.2"), the supplement or appendix
# the list belongs to ("Supplementary References", "Appendix B: References",
# "SI References"), and a note after it ("References (Level 1 Heading)",
# "References Cited").
_NUMBERING_RE = re.compile(r"\s*(?:\d{1,2}(?:\.\d{1,2})+\.?|[IVXLC]{1,7})\s+")
_LIST_OWNER_RE = re.compile(
    r"(?:(?:online\s+)?supplement(?:ary|al)?(?:\s+(?:information|materials?))?"
    r"|supporting\s+information|SI|appendix(?:\s+[A-Z\d]{1,3})?)\s*[.:]?\s+",
    re.IGNORECASE,
)
_NOTE_RE = re.compile(r"\s+(?:\([^()]*\)|cited\b.*)$", re.IGNORECASE)

# Headings that end a reference list when nothing marks them as headings.
_END_OF_LIST_RE = re.compile(
    r"\s*(?:appendix|appendices|annex|supplement(?:ary|al)?\b|supporting information"
    r"|author(?:s'|'s)? notes?\b|footnotes?$|endnotes?$|figure (?:captions|legends)"
    r"|extended data\b|tables?$|figures?$"
    r"|(?:tabla|tabela|tabelle|tableau|figura|abbildung|abb\.)\s*[A-Z]?\d)",
    re.IGNORECASE,
)
# An end-of-list heading is at most this many words, as many as a bold
# paragraph read as a heading may hold.
MAX_END_HEADING_WORDS = 20
_SUPPLEMENT_RE = re.compile(r"\s*(?:supplement|supporting information)", re.IGNORECASE)
# A year where an entry gives its date: in parentheses ("(2019)", "(2019a,
# May 3)"), or closed by punctuation ("2019.", "2019;12:"), but not as the
# end of a page range ("1601-1612."); "n.d.", "in press", "forthcoming".
_ENTRY_DATE_RE = re.compile(
    r"\((?:1[6-9]|20)\d{2}[a-z]?\b[^()]{0,30}\)"
    r"|(?<![\d‐‑–—-])\b(?:1[6-9]|20)\d{2}[a-z]?[.,;](?!\d)"
    r"|\bn\.\s?d\.|\bin press\b|\bforthcoming\b",
    re.IGNORECASE,
)
# An entry's opening: a list number ("[12]", "12.", "(12)"), a same-author
# dash, or a byline: a capitalized name (after any lowercase particle) followed
# by a comma, a full stop, initials, "&", "et al" or an opening parenthesis.
_PARTICLE = r"(?:van|von|de|der|den|del|della|du|di|da|dos|das|la|le|el|al|ten|ter|bin|ibn)"
_NAME = rf"(?:{_PARTICLE}\s+)*[^\W\d_a-z][^\s,.;:()]*"
_ENTRY_START_RE = re.compile(
    r"\s*(?:\[\d{1,4}\]|\(\d{1,4}\)|\d{1,4}[.)]?\s"
    r"|[-‐‑–—―_]{2,}|[–—―]\s?[.,]"
    rf"|{_NAME}(?:[ -]{_NAME})*\s*(?:,|\.|\s[A-Z]{{1,3}}\b|\s\(|\s&|\set al))"
)


@dataclass(frozen=True)
class ReferenceParagraph:
    """One paragraph under a references heading."""

    text: str  # as the parser reads it, line breaks as spaces
    lines: tuple[str, ...] = ()  # the text split at its explicit line breaks
    section: int = 0  # the parser's id of the references section it is in


def is_reference_list_heading(text: str) -> bool:
    """Whether *text* is a reference list's name ("References", "7. Literature
    Cited", "Supplementary References"), not a heading or entry that only
    holds a reference-list word ("Self-References in Memory", "Smith, J.
    (2019). A bibliography of memory.")."""
    name = " ".join(text.split())
    if len(name) > MAX_HEADING_CHARS:
        return False
    for prefix in (_NUMBERING_RE, _LIST_OWNER_RE):
        match = prefix.match(name)
        if match:
            name = name[match.end() :]
    return reads_as_reference_heading(name) or reads_as_reference_heading(_NOTE_RE.sub("", name))


def opens_an_entry(text: str) -> bool:
    """Whether *text* opens the way a reference entry does."""
    return _ENTRY_START_RE.match(text) is not None


def _reads_as_end_heading(text: str) -> bool:
    """Whether an end-of-list word opens a heading ("Appendix A",
    "Supplementary Information") rather than an entry ("Supplementary
    Nutrition Assistance Program. (2020). ..."): short, with no year and no
    byline."""
    return (
        _END_OF_LIST_RE.match(text) is not None
        and len(text.split()) <= MAX_END_HEADING_WORDS
        and YEARISH_RE.search(text) is None
        and not _looks_like_author_date_start(text)
    )


def _ends_the_list(text: str) -> bool:
    return bool(
        reads_as_float_label(text)
        or (starts_as_caption(text) and not YEARISH_RE.search(text))
        or _reads_as_end_heading(text)
    )


def _entries_of(paragraph: ReferenceParagraph) -> list[str]:
    """The paragraph, or its lines when its line breaks separate entries."""
    lines = paragraph.lines
    if (
        len(lines) > 1
        and " ".join(" ".join(lines).split()) == " ".join(paragraph.text.split())
        and all(opens_an_entry(line) and _ENTRY_DATE_RE.search(line) for line in lines)
    ):
        return list(lines)
    return [paragraph.text]


def reference_entries(
    paragraphs: list[ReferenceParagraph],
) -> tuple[list[str] | None, str]:
    """The entries of a reference list, one per paragraph, when the paragraphs
    pass the structure check; ``None`` (left to the configured segmenter)
    otherwise.

    Returns the entries and a reason: ``"ok"``, ``"too_few"`` or
    ``"year_coverage"``.
    """
    entries: list[str] = []
    texts = [paragraph.text.strip() for paragraph in paragraphs]
    ended: int | None = None  # the section whose list has ended
    for index, (paragraph, text) in enumerate(zip(paragraphs, texts, strict=True)):
        if not text:
            continue
        if is_reference_list_heading(text):
            # "References" typed as a paragraph, after a supplement under the
            # same heading: its list starts here.
            ended = None
            continue
        if paragraph.section == ended:
            continue
        if entries and _ends_the_list(text):
            following = next((t for t in texts[index + 1 :] if t), "")
            if (
                _SUPPLEMENT_RE.match(text)
                and opens_an_entry(following)
                and YEARISH_RE.search(following)
            ):
                continue  # "Supplementary Materials" over the supplement's references
            ended = paragraph.section
            continue
        entries.extend(_entries_of(paragraph))
    if len(entries) < MIN_ENTRIES:
        return None, "too_few"
    dated = sum(1 for entry in entries if YEARISH_RE.search(entry))
    if dated < MIN_YEAR_SHARE * len(entries):
        return None, "year_coverage"
    return entries, "ok"
